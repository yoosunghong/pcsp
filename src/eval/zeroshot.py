"""
Zero-shot persona consistency — eval/zeroshot.py  ★ KEY METRIC

Evaluates the trained PCSP policy on 60 test personas that were NEVER seen
during training (data/personas/test_60.json).

Two complementary metrics:

1. **Intra-persona coherence** (consistency):
   Trajectories generated by the same test persona should cluster together
   in trajectory-embedding space.  Measured as the ratio of intra-persona
   similarity to inter-persona similarity (>1 = consistent).

2. **Zero-shot classification accuracy**:
   For each test trajectory, find the nearest persona among ALL 60 test
   personas in policy.persona_proj(e_llm) space.  Top-1 accuracy.
   This tests whether the policy correctly distinguishes unseen personas.

3. **Train vs test consistency gap**:
   Compare classification accuracy on train_240 vs test_60.  A small gap
   indicates good generalisation.

Usage:
    python src/eval/zeroshot.py \
        --policy results/pcsp/full/policy.pt \
        --traj_enc results/pcsp/full/traj_encoder.pt \
        --train_personas data/personas/train_240.json \
        --test_personas  data/personas/test_60.json \
        --embeddings results/embeddings/persona_embeddings_300.npy \
        --n_episodes 5 --device cuda
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import torch
import torch.nn.functional as F
from typing import Callable

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from src.env.mini_inzoi import MiniInzoiEnv, PersonaConfig, N_ACTIONS
from src.models.trajectory_encoder import TrajectoryEncoder
from src.training.pcsp_trainer import PCSPActorCritic
from src.eval.consistency import _rollout_persona, _encode_trajectories
from src.eval.human_eval import wilson_ci

SPLITS_DIR = Path("data/personas/splits")
SPLIT_FAMILIES = ("unseen_occupation", "unseen_archetype", "unseen_combo")

OBS_DIM = 20
N_ACTS  = N_ACTIONS  # 12
LLM_DIM = 1024


def zero_shot_consistency(
    policy:              PCSPActorCritic,
    traj_encoder:        TrajectoryEncoder,
    test_personas_data:  list[dict],
    all_embeddings:      np.ndarray,       # (300, LLM_DIM)
    n_episodes:          int  = 5,
    device:              str  = "cuda",
    seed:                int  = 1000,
    n_agents:            int  = 4,
    env_factory:         Callable | None = None,
) -> dict:
    """
    Evaluate PCSP on 60 unseen test personas.

    Returns:
        accuracy:           top-1 k-NN classification accuracy on test personas
        intra_cos_mean:     mean cosine sim between trajectories of same persona
        inter_cos_mean:     mean cosine sim between trajectories of different personas
        coherence_ratio:    intra / inter (>1 = consistent)
        per_persona_acc:    per-persona accuracy list
        n_personas:         number of test personas evaluated
        n_trajectories:     total trajectories collected
    """
    dev = torch.device(device if torch.cuda.is_available() else "cpu")
    policy.to(dev).eval()
    traj_encoder.to(dev).eval()

    # Build persona projection embeddings for all test personas
    e_llm_test = torch.FloatTensor(
        all_embeddings[[p["id"] - 1 for p in test_personas_data]].astype(np.float32)
    ).to(dev)                                                  # (N_test, LLM_DIM)
    with torch.no_grad():
        p_embs = policy.persona_proj(e_llm_test).cpu()        # (N_test, 64) L2-normed

    all_traj_embs:  list[torch.Tensor] = []
    all_labels:     list[int]          = []
    per_persona_acc: list[float]       = []

    for p_idx, persona_dict in enumerate(test_personas_data):
        e_llm = torch.FloatTensor(
            all_embeddings[persona_dict["id"] - 1].astype(np.float32)
        ).unsqueeze(0).to(dev)                                  # (1, LLM_DIM)
        pcfg  = PersonaConfig.from_dict(persona_dict)

        trajs = _rollout_persona(
            policy, e_llm, pcfg, n_episodes, dev,
            seed_offset=seed + p_idx * 997,
            n_agents=n_agents,
            env_factory=env_factory,
        )
        if not trajs:
            continue

        t_embs = _encode_trajectories(traj_encoder, trajs, dev)  # (n_ep, 64)
        all_traj_embs.append(t_embs)
        all_labels.extend([p_idx] * len(trajs))

        print(f"  [{p_idx+1:3d}/{len(test_personas_data)}] "
              f"persona_id={persona_dict['id']}  trajs={len(trajs)}", flush=True)

    if not all_traj_embs:
        return {"accuracy": 0.0, "coherence_ratio": 0.0}

    traj_emb_mat = torch.cat(all_traj_embs, dim=0)            # (total_trajs, 64)
    labels_arr   = np.array(all_labels)
    n_total      = traj_emb_mat.shape[0]

    # k-NN top-1 classification against test persona projections
    sim_mat     = traj_emb_mat @ p_embs.T                     # (total_trajs, N_test)
    pred_labels = sim_mat.argmax(dim=1).numpy()
    correct     = (pred_labels == labels_arr).astype(float)
    accuracy    = float(correct.mean())

    for p_idx in range(len(test_personas_data)):
        mask = labels_arr == p_idx
        if mask.any():
            per_persona_acc.append(float(correct[mask].mean()))

    # Intra / inter cosine similarity (traj-to-traj)
    intra, inter = [], []
    for i in range(n_total):
        for j in range(i + 1, n_total):
            cos = float((traj_emb_mat[i] * traj_emb_mat[j]).sum())
            if labels_arr[i] == labels_arr[j]:
                intra.append(cos)
            else:
                inter.append(cos)

    intra_mean = float(np.mean(intra)) if intra else 0.0
    inter_mean = float(np.mean(inter)) if inter else 0.0
    coherence  = intra_mean / (inter_mean + 1e-8)

    return {
        "accuracy":         accuracy,
        "intra_cos_mean":   intra_mean,
        "inter_cos_mean":   inter_mean,
        "coherence_ratio":  coherence,
        "per_persona_acc":  per_persona_acc,
        "n_personas":       len(test_personas_data),
        "n_trajectories":   n_total,
    }


def compositional_zero_shot(
    policy:           PCSPActorCritic,
    traj_encoder:     TrajectoryEncoder,
    split_family:     str,
    all_embeddings:   np.ndarray,
    n_episodes:       int = 5,
    device:           str = "cuda",
    seed:             int = 1000,
    splits_dir:       Path = SPLITS_DIR,
    n_agents:         int = 4,
    env_factory:      Callable | None = None,
    split_suffix:     str = "",
) -> dict:
    """
    Run zero-shot consistency on one of the §4.3 compositional splits.

    Wraps ``zero_shot_consistency`` and adds:
      - Wilson 95% CI on the trajectory-level accuracy.
      - Split-family metadata so results from different runs can be aggregated.

    The caller is responsible for loading the policy/encoder weights that match
    the chosen split. ``unseen_occupation`` matches the existing PCSP-full
    training run (train_240/test_60), so its checkpoint can be reused. The
    other families require a new training run on their split's train file.
    """
    if split_family not in SPLIT_FAMILIES:
        raise ValueError(f"Unknown split family {split_family!r}; choose from {SPLIT_FAMILIES}.")

    test_path = ROOT / splits_dir / f"{split_family}{split_suffix}_test.json"
    if not test_path.exists():
        raise FileNotFoundError(
            f"{test_path} not found. Run scripts/build_compositional_splits.py first."
        )
    with open(test_path, encoding="utf-8") as f:
        test_personas = json.load(f)

    result = zero_shot_consistency(
        policy, traj_encoder, test_personas, all_embeddings,
        n_episodes=n_episodes, device=device, seed=seed,
        n_agents=n_agents, env_factory=env_factory,
    )
    accuracy = float(result.get("accuracy", 0.0))
    n_traj = int(result.get("n_trajectories", 0))
    k = int(round(accuracy * n_traj))
    lo, hi = wilson_ci(k, n_traj) if n_traj else (0.0, 0.0)
    result["wilson_ci_95"] = [lo, hi]
    result["split_family"] = split_family
    result["split_suffix"] = split_suffix
    result["random_chance"] = 1.0 / max(1, len(test_personas))
    return result


def zeroshot_vs_train(
    policy:              PCSPActorCritic,
    traj_encoder:        TrajectoryEncoder,
    train_personas_data: list[dict],
    test_personas_data:  list[dict],
    all_embeddings:      np.ndarray,
    n_episodes:          int  = 5,
    n_train_sample:      int  = 24,     # sample subset of train personas to keep runtime similar
    device:              str  = "cuda",
    n_agents:            int  = 4,
    env_factory:         Callable | None = None,
) -> dict:
    """
    Compare zero-shot accuracy (test_60) vs in-distribution accuracy (sample of train_240).
    Returns both results plus the generalisation gap.
    """
    dev = torch.device(device if torch.cuda.is_available() else "cpu")
    policy.to(dev).eval()
    traj_encoder.to(dev).eval()

    from src.eval.consistency import persona_classification_accuracy

    print("\n=== In-distribution (train sample) ===")
    train_result = persona_classification_accuracy(
        policy, traj_encoder, train_personas_data, all_embeddings,
        n_episodes=n_episodes,
        n_personas=n_train_sample,
        device=device,
        seed=0,
        n_agents=n_agents,
        env_factory=env_factory,
    )

    print("\n=== Zero-shot (test_60) ===")
    test_result = zero_shot_consistency(
        policy, traj_encoder, test_personas_data, all_embeddings,
        n_episodes=n_episodes,
        device=device,
        seed=1000,
        n_agents=n_agents,
        env_factory=env_factory,
    )

    gap = train_result["accuracy"] - test_result["accuracy"]

    return {
        "train": train_result,
        "test":  test_result,
        "generalisation_gap": float(gap),
    }


# ── CLI ───────────────────────────────────────────────────────────────────────

def _parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--policy",          default="results/pcsp/full/policy.pt")
    p.add_argument("--traj_enc",        default="results/pcsp/full/traj_encoder.pt")
    p.add_argument("--train_personas",  default="data/personas/train_240.json")
    p.add_argument("--test_personas",   default="data/personas/test_60.json")
    p.add_argument("--embeddings",      default="results/embeddings/persona_embeddings_300.npy")
    p.add_argument("--n_episodes",      type=int, default=5)
    p.add_argument("--n_train_sample",  type=int, default=24)
    p.add_argument("--compare",         action="store_true",
                   help="Compare train vs test (generalisation gap)")
    p.add_argument("--split_family",    choices=list(SPLIT_FAMILIES) + ["legacy"],
                   default="legacy",
                   help="Which §4.3 compositional split to evaluate; 'legacy' uses --test_personas.")
    p.add_argument("--split_suffix",    default="",
                   help="Suffix on the split filename (e.g. '_v3' for v3-aligned splits).")
    p.add_argument("--device",          default="cuda")
    p.add_argument("--obs_dim",         type=int, default=OBS_DIM,
                   help="Observation dim for the loaded checkpoint (v1=20, v3 base=33, v3 large=69).")
    p.add_argument("--n_actions",       type=int, default=N_ACTS,
                   help="Action count for the loaded checkpoint (v1=12, v3=20).")
    p.add_argument("--env_variant",     choices=("v1", "v3"), default="v1",
                   help="Which env class to roll out with; v1 uses MiniInzoiEnv, v3 uses MiniInzoiV3Env.")
    p.add_argument("--n_agents",        type=int, default=4,
                   help="Number of agents the env is constructed with.")
    return p.parse_args()


if __name__ == "__main__":
    args = _parse_args()

    with open(ROOT / args.train_personas) as f:
        train_data = json.load(f)
    with open(ROOT / args.test_personas) as f:
        test_data = json.load(f)
    all_emb = np.load(ROOT / args.embeddings)

    policy = PCSPActorCritic(args.obs_dim, args.n_actions)
    policy.load_state_dict(torch.load(ROOT / args.policy, map_location="cpu"))

    traj_enc = TrajectoryEncoder(args.obs_dim, args.n_actions)
    traj_enc.load_state_dict(torch.load(ROOT / args.traj_enc, map_location="cpu"))

    env_factory = None
    if args.env_variant == "v3":
        from src.env.mini_inzoi_v3 import MiniInzoiV3Env

        def env_factory(personas):
            return MiniInzoiV3Env(personas=personas, max_steps=200)

    if args.compare:
        result = zeroshot_vs_train(
            policy, traj_enc,
            train_data, test_data, all_emb,
            n_episodes=args.n_episodes,
            n_train_sample=args.n_train_sample,
            device=args.device,
            n_agents=args.n_agents,
            env_factory=env_factory,
        )
    elif args.split_family != "legacy":
        suffix = args.split_suffix
        print(f"=== Compositional zero-shot ({args.split_family}{suffix}) ===")
        result = compositional_zero_shot(
            policy, traj_enc, args.split_family, all_emb,
            n_episodes=args.n_episodes,
            device=args.device,
            n_agents=args.n_agents,
            env_factory=env_factory,
            split_suffix=suffix,
        )
    else:
        print("=== Zero-shot consistency (test_60) ===")
        result = zero_shot_consistency(
            policy, traj_enc, test_data, all_emb,
            n_episodes=args.n_episodes,
            device=args.device,
            n_agents=args.n_agents,
            env_factory=env_factory,
        )

    print(json.dumps(result, indent=2))
